#!/usr/bin/env python3
"""Writes listgen.h, the C form of cmdlist.build_list's constant part (FIELDS, PROFILE_1080P, IDR_FIELDS, P_FIELDS):
one source of truth, tests/test_h265cmdlist.py checks that listgen.h is up to date and that h265_list_build in C makes
the same lists as build_list.   python3 gen_listgen.py > listgen.h"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cmdlist as c


def words(fields):
    return c.encode(fields)[:c.PARAM_WORDS]


def main():
    base = dict(c.PROFILE_1080P)
    base.update({'qp': 0, 'sp_38': 0})
    idr = dict(base); idr.update(c.IDR_FIELDS)
    p = dict(base); p.update(c.P_FIELDS)
    wi, wp = words(idr), words(p)
    out = ['/* listgen.h: generated by gen_listgen.py from cmdlist.py (do not edit): the parameter words 0x00-0x1f of',
           ' * an IDR and of a P command list at 1920x1080 (H.265), then at 640x360 (H.264), with qp = 0 and POC 0; h265_list_build',
           ' * and h264_list_build set the rest. */',
           '#ifndef LISTGEN_H', '#define LISTGEN_H', '#include <stdint.h>', '',
           'static const uint32_t LISTGEN_IDR[32] = {']
    out += ['\t' + ', '.join('0x%08x' % x for x in wi[i:i + 8]) + ',' for i in range(0, 32, 8)]
    out += ['};', '', 'static const uint32_t LISTGEN_P[32] = {']
    out += ['\t' + ', '.join('0x%08x' % x for x in wp[i:i + 8]) + ',' for i in range(0, 32, 8)]
    out += ['};', '']
    for label, res_name, prof in (
        ('640x360 H.264 (the sub stream)', 'H264', c.PROFILE_H264_360P),
        ('1280x720 H.264', 'H264_720P', c.PROFILE_H264_720P),
        ('1920x1080 H.264 (the main stream)', 'H264_1080P', c.PROFILE_H264_1080P),
    ):
        base = dict(prof)
        idr = dict(base); idr.update(c.H264_IDR_FIELDS)
        p = dict(base); p.update(c.H264_P_FIELDS)
        for name, f in ((f'LISTGEN_{res_name}_IDR', idr), (f'LISTGEN_{res_name}_P', p)):
            w = words(f)
            out += [f'/* {label}, qp = 0, sp_8c = 0, sp_d8 = 0, POC 0 */',
                    'static const uint32_t %s[32] = {' % name]
            out += ['\t' + ', '.join('0x%08x' % x for x in w[i:i + 8]) + ',' for i in range(0, 32, 8)]
            out += ['};', '']
    out += ['#endif', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
