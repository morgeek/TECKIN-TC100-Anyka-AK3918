def quant_zigzag(quality, base):
    scale = 5000 // quality if quality < 50 else 200 - 2 * quality
    out = []
    for i in range(64):
        v = (scale * base[ZIGZAG[i]] + 50) // 100
        out.append(1 if v == 0 else min(v, 255))
    return out


def quant_recip(qz):
    """16-bit reciprocals, natural order, as the hardware wants them"""
    r = [0] * 64
    for i in range(64):
        r[ZIGZAG[i]] = ((0x10000 + (qz[i] >> 1)) // qz[i] - 1) & 0xffff
    return r


def huffman_words(counts, symbols, ac):
    entries = []
    code = 0; k = 0
    for ln in range(1, 17):
        for _ in range(counts[ln - 1]):
            nxt = symbols[k + 1] if k + 1 < len(symbols) else 0xff
            entries.append((symbols[k], code, ln, nxt)); code += 1; k += 1
        code <<= 1
    size = 162 if ac else 12
    words = [0] * size
    for sym, code, ln, nxt in entries:
        if ac:
            run, sz = sym >> 4, sym & 15
            idx = 161 if sym == 0x00 else 160 if sym == 0xf0 else run + 16 * (sz - 1)
        else:
            idx = sym
        words[idx] = ((ln - 1) << 24) | (code << 8) | nxt
    return words


def parse_dqt(jpeg):
    i = 2; out = []
    while i + 4 < len(jpeg) and jpeg[i] == 0xff:
        m = jpeg[i + 1]; l = int.from_bytes(jpeg[i + 2:i + 4], 'big')
        if m == 0xdb: out.append(list(jpeg[i + 5:i + 2 + l]))
        if m == 0xda: break
        i += 2 + l
    return out


def check(jpeg_path, lib_path=None):
    ok = True
    dq = parse_dqt(open(jpeg_path, 'rb').read())
    q = [Q for Q in range(1, 101) if quant_zigzag(Q, LUMA) == dq[0] and quant_zigzag(Q, CHROMA) == dq[1]]
    print('quantisation: file DQT reproduced with quality', q or 'NONE'); ok &= bool(q)
    if lib_path:
        lib = open(lib_path, 'rb').read()
        want = {'AC_LUMA': (0x435bc, 162, AC_LUMA, True), 'DC_LUMA': (0x43844, 12, DC_LUMA, False),
                'AC_CHROMA': (0x43874, 162, AC_CHROMA, True), 'DC_CHROMA': (0x43afc, 12, DC_CHROMA, False)}
        for name, (off, n, tab, ac) in want.items():
            have = list(struct.unpack('<%dI' % n, lib[off:off + 4 * n]))
            same = have == huffman_words(tab[0], tab[1], ac)
            print('huffman %-9s %s' % (name, 'identical to the library table' if same else 'DIFFERENT')); ok &= same
        print('library offsets are those of libakv_encode V2.2.16 (.rodata)')
    return ok


