#!/usr/bin/env python3
"""Write jpeg_std_tables.h (used by jpegenc.c) from jpeg_hw_tables.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jpeg_hw_tables as t

def arr(name, vals, fmt='0x%x', per=8, typ='static const unsigned int'):
    s = '%s %s[%d] = {\n' % (typ, name, len(vals))
    for i in range(0, len(vals), per):
        s += '\t' + ', '.join(fmt % v for v in vals[i:i + per]) + ',\n'
    return s + '};\n\n'

out = ('/* Generated by gen_tables_h.py from jpeg_hw_tables.py (ITU-T T.81 Annex K tables). Do not edit. */\n'
       '#ifndef JPEG_STD_TABLES_H\n#define JPEG_STD_TABLES_H\n\n')
out += arr('zigzag', t.ZIGZAG, '%d', 16, 'static const unsigned char')
out += arr('quant_luma', t.LUMA, '%d', 16, 'static const unsigned char')
out += arr('quant_chroma', t.CHROMA, '%d', 16, 'static const unsigned char')
out += arr('hw_ac_luma', t.huffman_words(*t.AC_LUMA, True))
out += arr('hw_dc_luma', t.huffman_words(*t.DC_LUMA, False))
out += arr('hw_ac_chroma', t.huffman_words(*t.AC_CHROMA, True))
out += arr('hw_dc_chroma', t.huffman_words(*t.DC_CHROMA, False))
for nm, tab in (('dht_dc_luma', t.DC_LUMA), ('dht_ac_luma', t.AC_LUMA),
                ('dht_dc_chroma', t.DC_CHROMA), ('dht_ac_chroma', t.AC_CHROMA)):
    out += arr(nm, tab[0] + tab[1], '%d', 16, 'static const unsigned char')
out += '#endif\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'jpeg_std_tables.h'), 'w').write(out)
