#!/usr/bin/env python3
"""Generates aacenc_tab.h: the AAC Huffman code tables used by aacenc.c.

The 11 spectral codebooks and the scale factor codebook are data defined by ISO/IEC 14496-3 (13818-7); they are read
here from FFmpeg's libavcodec/aactab.c (LGPL-2.1-or-later, Copyright (c) 2005-2007 Oded Shimon, Maxim Gavrilov), which
may be redistributed under the GPL version 2 of this project. Only the bare numbers are taken, nothing else.
Usage: python3 aacenc_tab_gen.py path/to/aactab.c > aacenc_tab.h
"""
import re
import sys

src = open(sys.argv[1]).read()


def arr(name):
    m = re.search(r"\b" + name + r"(?:\[\d*\])?\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("missing " + name)
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1))]


sizes = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289]
codes, bits, off = [], [], []
for i in range(11):
    c, b = arr("codes%d" % (i + 1)), arr("bits%d" % (i + 1))
    assert len(c) == len(b) == sizes[i], (i, len(c), len(b))
    off.append(len(codes))
    codes += c
    bits += b
sfc, sfb = arr("ff_aac_scalefactor_code"), arr("ff_aac_scalefactor_bits")
assert len(sfc) == len(sfb) == 121
swb = arr("swb_offset_1024_8")
assert len(swb) == 41 and swb[-1] == 1024


def dump(t, name, vals, per=12, fmt="%d"):
    print("static const %s %s[%d] = {" % (t, name, len(vals)))
    for i in range(0, len(vals), per):
        print("\t" + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    print("};")


print("/* aacenc_tab.h: generated by aacenc_tab_gen.py, do not edit. AAC Huffman codebooks (ISO/IEC 14496-3 tables, numbers read")
print(" * from FFmpeg libavcodec/aactab.c, LGPL-2.1-or-later) and the 8 kHz long-block scale factor bands. */")
dump("uint16_t", "aac_hcode", codes, 10, "0x%x")
dump("uint8_t", "aac_hbits", bits, 24)
print("static const uint16_t aac_hoff[11] = { %s };" % ", ".join(str(o) for o in off))
dump("uint32_t", "aac_sfcode", sfc, 8, "0x%x")
dump("uint8_t", "aac_sfbits", sfb, 24)
dump("uint16_t", "aac_swb8k", swb, 12)
