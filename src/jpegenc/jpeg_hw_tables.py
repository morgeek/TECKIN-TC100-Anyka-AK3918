"""Tables of the AK3918EV300 hardware JPEG engine (Allegro DVT JPEG core), derived
from the JPEG standard, and checks against a vendor JPEG / library.

What is derived here (all verified, see `--check`):
  * quantisation tables from a quality 1..100 (libjpeg scaling of the Annex K tables):
      scale = 5000/Q (Q < 50) else 200 - 2Q ; q = clamp((scale * base[zigzag[i]] + 50) / 100, 1, 255)
    stored in zigzag order (the DQT of the file), then, for the hardware, the reciprocal
      r = (0x10000 + q/2) / q - 1   (16 bit)   at index zigzag[i]   (natural order)
  * Huffman tables as 32-bit words, one per symbol:
      word = (len - 1) << 24 | code << 8 | next
    where `next` is the symbol that follows in the DHT symbol list (0xff after the last one).
    AC tables are indexed by run + 16 * (size - 1) (EOB = 161, ZRL = 160), DC tables by the size category.

The hardware also needs the 11 control words at 0x200283c0 (see README.md).

Usage: jpeg_hw_tables.py --check JPEG [libakv_encode.so]   verify against a vendor JPEG (and library)
"""
